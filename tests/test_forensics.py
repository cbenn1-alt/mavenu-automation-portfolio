class TestMigrationRollback:
    def test_rollback_for_real(self, tmp_path):
        db_path = str(tmp_path / "rollback.db")
        conn = get_connection(db_path)
        run_migrations(conn)
        assert "016_forensics.sql" in [
            r["name"] for r in
            conn.execute("SELECT name FROM schema_migrations").fetchall()
        ]
        # create real S03 rows before rolling back
        fx_dir = str(tmp_path / "fx")
        f.generate_synthetic_case(fx_dir)
        case = f.open_case(conn, clock=FIXED_CLOCK, **INTAKE_KWARGS)
        f.run_acquisition(conn, case["id"], os.path.join(fx_dir, "tree"),
                          clock=FIXED_CLOCK)
        assert conn.execute("SELECT COUNT(*) AS c FROM forensics_cases"
                            ).fetchone()["c"] == 1

        assert rollback_migration(conn, "016_forensics.sql") is True

        tables = {r["name"] for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table'").fetchall()}
        for t in ("forensics_cases", "forensics_acquisitions",
                  "forensics_artifacts", "forensics_timeline_events",
                  "forensics_hypotheses", "forensics_reports",
                  "forensics_hashchain"):
            assert t not in tables, t

        # re-apply works
        applied = run_migrations(conn)
        assert "016_forensics.sql" in applied
        tables = {r["name"] for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table'").fetchall()}
