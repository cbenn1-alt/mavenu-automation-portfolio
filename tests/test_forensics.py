class TestAcquisition:
    def test_acquire_ok(self, conn, cased, case_dir):
        acq = f.run_acquisition(conn, cased["id"], case_dir["tree"], clock=FIXED_CLOCK)
        assert acq["file_count"] == 3
        assert acq["total_bytes"] > 0
        assert len(acq["manifest_hash"]) == 64
        assert len(acq["start_hash"]) == 64
        assert acq["manifest_hash"] != acq["start_hash"]
        assert sorted(acq["manifest"]) == [
            "home/alvarez/docs/report_final.docx",
            "home/alvarez/downloads/installer_update.exe",
            "var/log/app.log",
        ]
        assert f.get_case(conn, cased["id"])["status"] == "acquired"
        steps = [e["step"] for e in f.get_chain(conn, cased["id"])]
        assert steps == ["case.opened", "acquisition.start", "acquisition.complete"]

    def test_manifest_hash_deterministic(self, conn, case_dir):
        c1 = f.open_case(conn, clock=FIXED_CLOCK, **INTAKE_KWARGS)
        c2 = f.open_case(conn, clock=FIXED_CLOCK, **INTAKE_KWARGS)
        a1 = f.run_acquisition(conn, c1["id"], case_dir["tree"], clock=FIXED_CLOCK)
        a2 = f.run_acquisition(conn, c2["id"], case_dir["tree"], clock=FIXED_CLOCK)
        assert a1["manifest_hash"] == a2["manifest_hash"]

    def test_reacquire_rejected(self, conn, cased, case_dir, acquired):
        with pytest.raises(f.ForensicsError):
            f.run_acquisition(conn, cased["id"], case_dir["tree"])

    def test_bad_source_dir_rejected(self, conn, cased, tmp_path):
        with pytest.raises(ValidationError):
            f.run_acquisition(conn, cased["id"], str(tmp_path / "nope"))

    def test_unknown_case_rejected(self, conn, case_dir):
        with pytest.raises(f.ForensicsError):
            f.run_acquisition(conn, 9999, case_dir["tree"])


