class TestIntegrity:
    def test_verify_ok_on_untampered(self, conn, acquired, case_dir):
        result = f.verify_acquisition(conn, acquired["id"], case_dir["tree"])
        assert result["ok"] is True
        assert result["mismatches"] == []
        assert result["missing"] == []
        assert result["extra"] == []
        assert result["manifest_match"] is True

    def test_modify_detected(self, conn, acquired, case_dir):
        target = os.path.join(case_dir["tree"], "var/log/app.log")
        with open(target, "a", encoding="utf-8") as fh:
            fh.write("TAMPERED LINE\n")
        result = f.verify_acquisition(conn, acquired["id"], case_dir["tree"])
        assert result["ok"] is False
        assert result["mismatches"] == ["var/log/app.log"]
        assert result["manifest_match"] is False

    def test_delete_detected(self, conn, acquired, case_dir):
        os.remove(os.path.join(case_dir["tree"], "home/alvarez/docs/report_final.docx"))
        result = f.verify_acquisition(conn, acquired["id"], case_dir["tree"])
        assert result["ok"] is False
        assert result["missing"] == ["home/alvarez/docs/report_final.docx"]

    def test_add_detected(self, conn, acquired, case_dir):
        with open(os.path.join(case_dir["tree"], "planted_later.txt"),
                  "w", encoding="utf-8") as fh:
            fh.write("not in the manifest\n")
        result = f.verify_acquisition(conn, acquired["id"], case_dir["tree"])
        assert result["ok"] is False
        assert result["extra"] == ["planted_later.txt"]

    def test_chain_verify_ok(self, conn, acquired):
        verdict = f.verify_chain(conn, acquired["case_id"])
        assert verdict["ok"] is True
        assert verdict["entries"] == 3

    def test_chain_tamper_detected(self, conn, acquired):
        conn.execute(
            "UPDATE forensics_hashchain SET payload_hash = ? "
            "WHERE case_id = ? AND step = 'acquisition.complete'",
            ("f" * 64, acquired["case_id"]),
        )
        conn.commit()
        verdict = f.verify_chain(conn, acquired["case_id"])
        assert verdict["ok"] is False
        assert verdict["step"] == "acquisition.complete"

    def test_chain_reorder_detected(self, conn, acquired):
        conn.execute(
            "UPDATE forensics_hashchain SET prev_hash = ? "
            "WHERE case_id = ? AND step = 'acquisition.complete'",
            ("e" * 64, acquired["case_id"]),
        )
        conn.commit()
        verdict = f.verify_chain(conn, acquired["case_id"])
        assert verdict["ok"] is False


