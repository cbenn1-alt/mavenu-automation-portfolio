class TestTimeline:
    def _full_examination(self, conn, acquired, case_dir):
        meta = _load(case_dir["meta_path"])
        f.extract_file_listing(conn, acquired["id"], meta, clock=FIXED_CLOCK)
        with open(os.path.join(case_dir["tree"], "var/log/app.log"),
                  encoding="utf-8") as fh:
            f.extract_log_events(conn, acquired["id"], fh.read(), clock=FIXED_CLOCK)
        blob = open(case_dir["blob_path"], "rb").read()
        f.carve_deleted(conn, acquired["id"], blob, _load(case_dir["freelist_path"]),
                        clock=FIXED_CLOCK)
        events = f.events_from_fixture(case_dir["target_dir"])
        return f.record_timeline(conn, acquired["case_id"], events, clock=FIXED_CLOCK)

    def test_build_sorts_chronologically(self):
        events = [
            {"ts": "2026-10-20T14:00:00+00:00", "source": "s",
             "event_type": "b", "summary": "second"},
            {"ts": "2026-10-20T13:00:00+00:00", "source": "s",
             "event_type": "a", "summary": "first"},
        ]
        tl = f.build_timeline(events)
        assert [e["summary"] for e in tl] == ["first", "second"]

    def test_build_rejects_incomplete_event(self):
        with pytest.raises(ValidationError):
            f.build_timeline([{"ts": "2026-10-20T13:00:00+00:00"}])

    def test_score_perfect_on_fixture(self, conn, acquired, case_dir):
        timeline = self._full_examination(conn, acquired, case_dir)
        truth = _load(case_dir["ground_truth_path"])["events"]
        score = f.score_timeline(timeline, truth)
        assert score["matched"] == 5
        assert score["total"] == 5
        assert score["score"] == 1.0
        assert f.get_case(conn, acquired["case_id"])["status"] == "analyzed"

    def test_score_tolerance(self):
        gt = [{"ts": "2026-10-20T14:00:00+00:00", "event_type": "x"}]
        within = [{"ts": "2026-10-20T14:00:59+00:00", "source": "s",
                   "event_type": "x", "summary": "s"}]
        beyond = [{"ts": "2026-10-20T14:01:01+00:00", "source": "s",
                   "event_type": "x", "summary": "s"}]
        assert f.score_timeline(within, gt)["score"] == 1.0     # 59s <= 60s
        assert f.score_timeline(beyond, gt)["score"] == 0.0     # 61s > 60s

    def test_score_requires_matching_type(self):
        gt = [{"ts": "2026-10-20T14:00:00+00:00", "event_type": "x"}]
        built = [{"ts": "2026-10-20T14:00:00+00:00", "source": "s",
                  "event_type": "y", "summary": "s"}]
        assert f.score_timeline(built, gt)["score"] == 0.0

    def test_timeline_persisted(self, conn, acquired, case_dir):
        timeline = self._full_examination(conn, acquired, case_dir)
        stored = f.get_timeline(conn, acquired["case_id"])
        assert len(stored) == len(timeline)
        assert stored[0]["ts"] <= stored[-1]["ts"]


