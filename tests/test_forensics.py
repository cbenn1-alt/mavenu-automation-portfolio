def _analyzed(conn, case_dir):
    """Drive a case through to the 'analyzed' stage."""
    case = f.open_case(conn, clock=FIXED_CLOCK, **INTAKE_KWARGS)
    acq = f.run_acquisition(conn, case["id"], case_dir["tree"], clock=FIXED_CLOCK)
    meta = _load(case_dir["meta_path"])
    f.extract_file_listing(conn, acq["id"], meta, clock=FIXED_CLOCK)
    with open(os.path.join(case_dir["tree"], "var/log/app.log"),
              encoding="utf-8") as fh:
        f.extract_log_events(conn, acq["id"], fh.read(), clock=FIXED_CLOCK)
    events = f.events_from_fixture(case_dir["target_dir"])
    f.record_timeline(conn, case["id"], events, clock=FIXED_CLOCK)
    return case


GOOD_FINDINGS = [
    {"kind": "fact",
     "text": "installer_update.exe was downloaded at 2026-10-20T14:02:11Z.",
     "evidence": ["var/log/app.log#L2"]},
    {"kind": "inference",
     "text": "The demo user executed the installer.",
     "evidence": ["var/log/app.log#L3"],
     "confidence": "high"},
]


class TestReport:
    def test_draft_ok(self, conn, case_dir):
        case = _analyzed(conn, case_dir)
        result = f.draft_report(conn, case["id"], GOOD_FINDINGS, clock=FIXED_CLOCK)
        assert result["audit"] == []
        assert "## Facts" in result["text"]
        assert "## Inferences" in result["text"]
        assert "[confidence: high]" in result["text"]
        assert f.get_case(conn, case["id"])["status"] == "reported"

    def test_inference_without_confidence_rejected(self, conn, case_dir):
        case = _analyzed(conn, case_dir)
        findings = [{"kind": "inference", "text": "Someone did something.",
                     "evidence": ["var/log/app.log#L1"]}]
        with pytest.raises(ValidationError):
            f.draft_report(conn, case["id"], findings, clock=FIXED_CLOCK)

    def test_inference_with_bad_confidence_rejected(self):
        issues = f.audit_findings([
            {"kind": "inference", "text": "t", "evidence": ["e"],
             "confidence": "certain"}])
        assert any(i["severity"] == "error" for i in issues)

    def test_fact_without_evidence_rejected(self):
        issues = f.audit_findings(
            [{"kind": "fact", "text": "t", "evidence": []}])
        assert any(i["severity"] == "error" for i in issues)

    def test_fact_with_confidence_is_warning_not_error(self, conn, case_dir):
        case = _analyzed(conn, case_dir)
        findings = [{"kind": "fact", "text": "A file exists.",
                     "evidence": ["home/alvarez/docs/report_final.docx"],
                     "confidence": "high"}]
        result = f.draft_report(conn, case["id"], findings, clock=FIXED_CLOCK)
        assert any(i["severity"] == "warning" for i in result["audit"])
        assert not any(i["severity"] == "error" for i in result["audit"])

    def test_unresolved_is_allowed_finding(self, conn, case_dir):
        case = _analyzed(conn, case_dir)
        findings = GOOD_FINDINGS + [
            {"kind": "inference",
             "text": "Attribution of the download to a specific person is unresolved.",
             "evidence": ["var/log/app.log#L2"],
             "confidence": "low"},
        ]
        result = f.draft_report(conn, case["id"], findings, clock=FIXED_CLOCK)
        assert "unresolved" in result["text"].lower()

    def test_facts_and_inferences_separated_in_text(self, conn, case_dir):
        case = _analyzed(conn, case_dir)
        result = f.draft_report(conn, case["id"], GOOD_FINDINGS, clock=FIXED_CLOCK)
        facts_idx = result["text"].index("## Facts")
        inf_idx = result["text"].index("## Inferences")
        assert facts_idx < inf_idx
        # the fact line must not carry a confidence tag
        fact_line = [l for l in result["text"].splitlines()
                     if "downloaded at" in l][0]
        assert "confidence" not in fact_line

    def test_report_requires_analyzed_stage(self, conn, cased):
        with pytest.raises(f.ForensicsError):
            f.draft_report(conn, cased["id"], GOOD_FINDINGS)

    def test_report_rejects_empty_findings(self, conn, case_dir):
        case = _analyzed(conn, case_dir)
        with pytest.raises(ValidationError):
            f.draft_report(conn, case["id"], [])

    def test_chain_verified_in_report(self, conn, case_dir):
        case = _analyzed(conn, case_dir)
        result = f.draft_report(conn, case["id"], GOOD_FINDINGS, clock=FIXED_CLOCK)
        assert "VERIFIED" in result["text"]

    def test_get_report(self, conn, case_dir):
        case = _analyzed(conn, case_dir)
        result = f.draft_report(conn, case["id"], GOOD_FINDINGS, clock=FIXED_CLOCK)
        report = f.get_report(conn, result["report_id"])
        assert len(report["findings"]) == 2
        assert report["audit"] == []


