class TestExamination:
    def test_file_listing_recovers_all_planted(self, conn, acquired, case_dir):
        meta = _load(case_dir["meta_path"])
        truth = _load(case_dir["ground_truth_path"])
        arts = f.extract_file_listing(conn, acquired["id"], meta, clock=FIXED_CLOCK)
        recovered = sorted(a["ref_path"] for a in arts)
        assert recovered == sorted(truth["planted_files"])  # 100% recovery
        assert f.get_case(conn, acquired["case_id"])["status"] == "examined"

    def test_mac_times_come_from_meta(self, conn, acquired, case_dir):
        meta = _load(case_dir["meta_path"])
        arts = f.extract_file_listing(conn, acquired["id"], meta, clock=FIXED_CLOCK)
        doc = next(a for a in arts
                   if a["ref_path"] == "home/alvarez/docs/report_final.docx")
        assert doc["mtime"] == meta["home/alvarez/docs/report_final.docx"]["mtime"]
        assert doc["ctime"] == meta["home/alvarez/docs/report_final.docx"]["ctime"]
        assert doc["atime"] == meta["home/alvarez/docs/report_final.docx"]["atime"]

    def test_log_parser_line(self):
        event = f.parse_log_line(
            "2026-10-20T14:02:11Z app=demo-agent event=download path=/x result=ok")
        assert event["event_type"] == "download"
        assert event["attrs"]["path"] == "/x"
        assert event["ts"].startswith("2026-10-20T14:02:11")

    @pytest.mark.parametrize("line", [
        "",
        "   ",
        "not a timestamp at all",
        "2026-10-20T14:02:11Z app=demo-agent result=ok",      # no event=
        "2026-13-99T99:99:99Z app=x event=y",                  # bad timestamp
    ])
    def test_log_parser_skips_garbage(self, line):
        assert f.parse_log_line(line) is None

    def test_log_parser_whole_log(self, conn, acquired, case_dir):
        with open(os.path.join(case_dir["tree"], "var/log/app.log"),
                  encoding="utf-8") as fh:
            text = fh.read()
        events = f.parse_log(text + "\nGARBAGE LINE\n\n")
        assert len(events) == 5
        arts = f.extract_log_events(conn, acquired["id"], text, clock=FIXED_CLOCK)
        assert len(arts) == 5
        assert arts[0]["event_type"] == "login"

    def test_carving_recovers_deleted(self, conn, acquired, case_dir):
        blob = open(case_dir["blob_path"], "rb").read()
        free_list = _load(case_dir["freelist_path"])
        truth = _load(case_dir["ground_truth_path"])
        recovered = f.carve_deleted(conn, acquired["id"], blob, free_list,
                                    clock=FIXED_CLOCK)
        assert sorted(r["ref_path"] for r in recovered) == truth["deleted_files"]
        assert all(r["hash_match"] for r in recovered)
        assert "secret_notes" in recovered[0]["preview"]

    def test_carving_detects_corruption(self, conn, acquired, case_dir):
        blob = open(case_dir["blob_path"], "rb").read()
        free_list = _load(case_dir["freelist_path"])
        free_list[0]["expected_sha256"] = "0" * 64  # wrong expectation
        recovered = f.carve_deleted(conn, acquired["id"], blob, free_list,
                                    clock=FIXED_CLOCK)
        assert recovered[0]["hash_match"] is False  # reported, not silent

    def test_carving_out_of_bounds_rejected(self, conn, acquired):
        with pytest.raises(ValidationError):
            f.carve_deleted(conn, acquired["id"], b"tiny",
                            [{"name": "x", "offset": 10, "size": 50,
                              "expected_sha256": "0" * 64}], clock=FIXED_CLOCK)

    def test_artifacts_traceable_to_acquisition(self, conn, acquired, case_dir):
        meta = _load(case_dir["meta_path"])
        f.extract_file_listing(conn, acquired["id"], meta, clock=FIXED_CLOCK)
        arts = f.list_artifacts(conn, acquired["id"])
        assert all(a["acquisition_id"] == acquired["id"] for a in arts)
        assert {a["kind"] for a in arts} == {"file"}


